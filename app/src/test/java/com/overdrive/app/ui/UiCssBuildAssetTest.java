package com.overdrive.app.ui;

import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

import java.io.IOException;
import java.nio.file.Files;
import org.junit.Test;

/** Contract for the Tailwind-built stylesheet (docs/superpowers/specs/2026-11-17-web-tailwind-rebuild-design.md). */
public class UiCssBuildAssetTest {

    static final String UI_CSS = "app/src/main/assets/web/shared/ui.css";
    static final String BANNER = "/* Generated by web-ui — do not edit. Run: cd web-ui && npm run build */";

    static String css() throws IOException {
        return WebThemeTokensAssetTest.read(UI_CSS);
    }

    @Test
    public void builtFileCarriesBanner() throws IOException {
        assertTrue(css().startsWith(BANNER));
    }

    @Test
    public void mockupLightTokens() throws IOException {
        String c = css();
        for (String t : new String[]{"--ui-page:#f4f6f8", "--ui-surface:#fff", "--ui-line:#e5e9ef",
                "--ui-ink:#182431", "--ui-muted:#667180", "--ui-accent:#db4f1c", "--ui-accent-text:#c2410c",
                "--ui-green:#257355", "--ui-sidebar-width:240px"}) {
            assertTrue(t, c.contains(t));
        }
    }

    @Test
    public void mockupDarkTokensAreTheDefault() throws IOException {
        // theme.js defaults to dark, so dark applies unless data-theme="light".
        String c = css();
        int at = c.indexOf(":root:not([data-theme=light])");
        assertTrue("dark block missing", at >= 0);
        for (String t : new String[]{"--ui-page:#191a1b", "--ui-surface:#242627", "--ui-ink:#f5f3f0",
                "--ui-accent:#ff8068", "--ui-green:#89c9aa"}) {
            assertTrue(t, c.indexOf(t, at) > 0);
        }
    }

    @Test
    public void sidebarWidthIsNotPinnedByTheThemeSelector() throws IOException {
        // A themed selector (:root[data-theme=light]) outranks the plain :root in the breakpoints,
        // which kept the sidebar 240px wide on narrow screens.
        String c = css();
        int at = c.indexOf("--ui-sidebar-width:240px");
        String selector = c.substring(c.lastIndexOf('}', at) + 1, c.lastIndexOf('{', at));
        assertTrue("240px is set on '" + selector + "'", selector.equals(":root"));
        assertTrue(c.contains("{:root{--ui-sidebar-width:200px}}"));
        assertTrue(c.contains("{:root{--ui-sidebar-width:72px}}"));
    }

    @Test
    public void noNetworkLoads() throws IOException {
        assertFalse(css().matches("(?s).*https?://.*"));
    }

    @Test
    public void utilitiesArePrefixed() throws IOException {
        String c = css();
        assertTrue(c.contains(".tw\\:flex{"));
        assertFalse(c.contains("}.flex{"));
    }

    @Test
    public void noPreflightWhileMigrating() throws IOException {
        assertFalse(css().contains("::file-selector-button"));
    }

    @Test
    public void dependenciesPinnedExactly() throws IOException {
        String p = WebThemeTokensAssetTest.read("web-ui/package.json");
        assertFalse(p.matches("(?s).*\"[~^][0-9].*"));
        assertTrue(Files.exists(WebThemeTokensAssetTest.locate("web-ui/package-lock.json")));
    }
}
