package com.overdrive.app.ui;

import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

import java.io.IOException;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.junit.Test;

/** Phosphor icons (owner's choice, 2026-11-17) bundled as one local sprite. */
public class PhosphorIconsAssetTest {

    static final String SPRITE = "app/src/main/assets/web/shared/ph-icons.js";
    static final String MAP = "web-ui/icons.json";

    @Test
    public void everyMappedIconIsInTheSprite() throws IOException {
        String sprite = WebThemeTokensAssetTest.read(SPRITE);
        Matcher key = Pattern.compile("\"([a-z0-9-]+)\"\\s*:").matcher(WebThemeTokensAssetTest.read(MAP));
        int n = 0;
        while (key.find()) {
            n++;
            assertTrue("sprite lacks " + key.group(1), sprite.contains("id=\\\"ph-" + key.group(1) + "\\\"")
                    || sprite.contains("id=\"ph-" + key.group(1) + "\""));
        }
        assertTrue("icon map is empty", n >= 24);
    }

    @Test
    public void spriteIsGeneratedAndLocal() throws IOException {
        String sprite = WebThemeTokensAssetTest.read(SPRITE);
        assertTrue(sprite.startsWith("/* Generated by web-ui — do not edit."));
        assertTrue(sprite.contains("window.phIcon = function"));
        String withoutNamespace = sprite.replace("http://www.w3.org/2000/svg", "");
        assertFalse("no remote loads", withoutNamespace.matches("(?s).*https?://.*"));
    }

    @Test
    public void licenceShipsWithTheIcons() throws IOException {
        assertTrue(WebThemeTokensAssetTest.read("app/src/main/assets/web/shared/icons/PHOSPHOR-LICENSE.txt")
                .contains("MIT License"));
    }

    @Test
    public void phosphorPinnedExactly() throws IOException {
        assertTrue(WebThemeTokensAssetTest.read("web-ui/package.json")
                .matches("(?s).*\"@phosphor-icons/core\": \"[0-9]+\\.[0-9]+\\.[0-9]+\".*"));
    }

    @Test
    public void navIconsExistInTheMap() throws IOException {
        String map = WebThemeTokensAssetTest.read(MAP);
        Matcher icon = Pattern.compile("icon: '([a-z0-9-]+)'")
                .matcher(WebThemeTokensAssetTest.read("app/src/main/assets/web/shared/app-shell.js"));
        while (icon.find()) {
            assertTrue("icons.json lacks nav icon " + icon.group(1), map.contains("\"" + icon.group(1) + "\""));
        }
    }
}
